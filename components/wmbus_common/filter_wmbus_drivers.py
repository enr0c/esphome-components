# pylint: disable=E0602
Import("env")  # noqa

import logging
import os
import re
import sys
from glob import glob


LOGGER = logging.getLogger(__name__)

# Make sure logs show up in ESPHome/PlatformIO output.
if not LOGGER.handlers:
    _handler = logging.StreamHandler(sys.stdout)
    _handler.setFormatter(logging.Formatter("%(levelname)s wmbus_common.pre: %(message)s"))
    LOGGER.addHandler(_handler)
    LOGGER.setLevel(logging.INFO)
    LOGGER.propagate = False


def _get_selected_drivers(env) -> set[str]:
    # Primary source: dedicated project option injected by ESPHome codegen.
    try:
        raw = env.GetProjectOption("custom_wmbus_include_drivers")
    except Exception:
        raw = None

    if not raw:
        return set()

    raw = str(raw).strip().strip('"').strip("'")
    return {name.strip() for name in raw.split(",") if name.strip()}


DRIVER_REGISTRY = "driver_registry.cpp"
DRIVER_ANCHOR_PATTERN = re.compile(
    r"\bvoid\s+(wmbus_anchor_driver_[A-Za-z0-9_]+)\s*\(\s*void\s*\)"
)


def _restore_driver_sources(src_dir, files_to_restore=None):
    restored = 0
    for off_path in glob(os.path.join(src_dir, "driver_*.cpp.off")):
        base = os.path.basename(off_path)[:-4]  # strip .off
        if files_to_restore is None or base in files_to_restore:
            os.rename(off_path, os.path.join(src_dir, base))
            restored += 1
    return restored


def _get_driver_anchor(src_dir, driver_name):
    driver_path = os.path.join(src_dir, f"driver_{driver_name}.cpp")
    with open(driver_path, encoding="utf-8") as driver_file:
        matches = DRIVER_ANCHOR_PATTERN.findall(driver_file.read())

    if len(matches) != 1:
        raise RuntimeError(
            f"Expected one driver anchor in {driver_path}, found {len(matches)}"
        )
    return matches[0]


def _write_driver_registry(src_dir, driver_names):
    anchors = sorted(_get_driver_anchor(src_dir, name) for name in driver_names)
    lines = ["// Auto-generated by filter_wmbus_drivers.py."]
    lines.extend(f"extern void {anchor}(void);" for anchor in anchors)
    lines.extend(["", "void wmbus_ensure_all_drivers(void) {"])
    lines.extend(f"    {anchor}();" for anchor in anchors)
    lines.append("}")
    lines.append("")

    registry_path = os.path.join(src_dir, DRIVER_REGISTRY)
    with open(registry_path, "w", encoding="utf-8", newline="\n") as registry_file:
        registry_file.write("\n".join(lines))


def _filter_drivers(src_dir, selected):
    registry_file = DRIVER_REGISTRY
    selected_files = {f"driver_{name}.cpp" for name in selected}
    files_to_restore = selected_files | {registry_file}
    off_before = len(glob(os.path.join(src_dir, "driver_*.cpp.off")))
    restored_count = _restore_driver_sources(src_dir, files_to_restore)

    _write_driver_registry(src_dir, selected)

    kept = []
    excluded_now = 0
    for path in glob(os.path.join(src_dir, "driver_*.cpp")):
        base = os.path.basename(path)
        if base == registry_file:
            continue
        if base in selected_files:
            kept.append(base)
            continue
        os.rename(path, path + ".off")
        excluded_now += 1

    already_off = max(0, off_before - restored_count)
    LOGGER.info(
        "selected_drivers=%s kept=%s excluded_now=%d already_off=%d",
        sorted(selected),
        sorted(kept),
        excluded_now,
        already_off,
    )


def main():
    # For ESPHome, component sources live under
    # $PROJECT_SRC_DIR/esphome/components/<component>.
    project_src_dir = env.subst("$PROJECT_SRC_DIR")
    src_dir = os.path.join(project_src_dir, "esphome", "components", "wmbus_common")

    if not os.path.isdir(src_dir):
        LOGGER.warning("src dir not found: %s", src_dir)
        return

    selected = _get_selected_drivers(env)
    if selected:
        LOGGER.info("filtering drivers in %s", src_dir)
        _filter_drivers(src_dir, selected)
        return

    restored_count = _restore_driver_sources(src_dir)
    driver_names = {
        os.path.basename(path)[len("driver_") : -len(".cpp")]
        for path in glob(os.path.join(src_dir, "driver_*.cpp"))
        if os.path.basename(path) != DRIVER_REGISTRY
    }
    _write_driver_registry(src_dir, driver_names)
    LOGGER.info(
        "no selected drivers; leaving all driver_*.cpp as-is (restored=%d)",
        restored_count,
    )


main()
